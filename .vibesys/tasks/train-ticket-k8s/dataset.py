"""train-ticket-k8s dataset: the seed and size of the task's fixture, and its digest.

The fixture itself (per record: a config, two stations, a train, the route between the
stations, a price and a trip, connected) is generated by the Go module
evaluator/internal/ttdata from these constants: the seed Job creates it through the
application's public API (evaluator/cmd/seed), and the generator rebuilds it from the
dataset file the benchmark writes, which is this value as JSON
({"seed": ..., "records": ..., "digest": ...}). The digest is the Go fixture's, so a
generator or a seed built from a different fixture refuses to run. The constants are part
of the task version: changing them changes the task.
"""

from __future__ import annotations

from dataclasses import dataclass

SEED = 0x7A1171C4E7
RECORDS = 32
DIGEST = "5c84e21c21b2b43a6fe01045502ef57b20ecf8a2481ee1aa766b3a5d3a107f4e"


@dataclass(frozen=True)
class Dataset:
    seed: int
    records: int
    digest: str


def generate() -> Dataset:
    return Dataset(SEED, RECORDS, DIGEST)
